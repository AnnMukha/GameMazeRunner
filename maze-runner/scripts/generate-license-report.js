"use strict";

const fs = require("fs");
const path = require("path");

const projectRoot = path.resolve(__dirname, "..");
const nodeModulesRoot = path.join(projectRoot, "node_modules");
const reportPath = path.join(projectRoot, "THIRD_PARTY_LICENSES.md");

const seen = new Set();
const rows = [];

function normalizeRepository(repository) {
  if (!repository) return "";
  if (typeof repository === "string") return repository;
  return repository.url || "";
}

function collectPackages(dir) {
  let entries = [];

  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }

  for (const entry of entries) {
    if (!entry.isDirectory() || entry.name === ".bin") {
      continue;
    }

    const fullPath = path.join(dir, entry.name);

    if (entry.name.startsWith("@")) {
      collectPackages(fullPath);
      continue;
    }

    const packageJsonPath = path.join(fullPath, "package.json");

    if (!fs.existsSync(packageJsonPath)) {
      continue;
    }

    try {
      const pkg = JSON.parse(fs.readFileSync(packageJsonPath, "utf8"));
      const key = `${pkg.name}@${pkg.version}`;

      if (seen.has(key)) {
        continue;
      }

      seen.add(key);
      rows.push({
        name: pkg.name,
        version: pkg.version,
        license: pkg.license || "UNKNOWN",
        repository: normalizeRepository(pkg.repository),
      });
    } catch {
      // Ignore unreadable package manifests in the generated report.
    }
  }
}

collectPackages(nodeModulesRoot);

rows.sort((left, right) => {
  const nameOrder = left.name.localeCompare(right.name);
  if (nameOrder !== 0) return nameOrder;
  return left.version.localeCompare(right.version);
});

const unknownPackages = rows.filter((pkg) => pkg.license === "UNKNOWN");

const lines = [
  "# Third-Party License Report",
  "",
  "Generated by `npm run licenses:report` using the installed `node_modules` tree.",
  "",
  `Generated at: ${new Date().toISOString()}`,
  `Total packages scanned: ${rows.length}`,
  `Packages without explicit license field: ${unknownPackages.length}`,
  "",
  "## Notes",
  "",
  "- This report inspects installed package manifests and records the `license` field when present.",
  "- Packages marked as `UNKNOWN` do not expose a direct `license` field in their local `package.json`.",
  "- The project code itself is licensed under MIT. See `LICENSE`.",
  "",
  "## Package List",
  "",
  "| Package | Version | License | Repository |",
  "| --- | --- | --- | --- |",
];

for (const pkg of rows) {
  lines.push(
    `| ${pkg.name} | ${pkg.version} | ${pkg.license} | ${pkg.repository || "-"} |`
  );
}

fs.writeFileSync(reportPath, `${lines.join("\n")}\n`, "utf8");

console.log(`License report written to ${reportPath}`);
